    o.append("不需要上传图片。每张是同一个人的四个视图。\n")
    for k in new_chars:
        o.append(f"### {k} {CHARS[k][0]}\n")
        o.append(block(SHEET_TMPL.format(desc=CHARS[k][4])))
        rows.append((k, CHARS[k][0] + "设定图", []))

    sec = 4
    for ch in CHAPTERS:
        o.append(f"---\n\n## {sec}. 第 {ch['no']} 章：{ch['name']}\n")
        o.append(ch["story"] + "\n")
        o.append(f"### {sec}.1 空镜底板\n")
        o.append("底板里不能有任何人和动物。提示词里列出的掩体是敌人出现和倒下的位置，必须都在。\n")
        for p in ch["plates"]:
            o.append(f"#### {p['id']} {p['title']}\n")
